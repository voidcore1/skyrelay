#!/usr/bin/env python3
"""Generate the SkyRelay contract artefacts from idl/skyrelay/v1/types.idl.

Stdlib only. Accepts a deliberately small IDL subset (see parse()); anything
else is an error with a line number. Run without arguments to write the
generated files, or with --check to fail if any committed file is stale.
"""
import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

IDL_PATH = "idl/skyrelay/v1/types.idl"
JSON_HPP = "lib/dds/include/skyrelay/dds/gen/v1_json.hpp"
VALID_HPP = "lib/dds/include/skyrelay/dds/gen/v1_valid_bits.hpp"
TS_PATH = "web/station/src/contract/v1.ts"
MD_PATH = "docs/contract/v1-fields.md"

BANNER = "Generated by tools/codegen/idl2gen.py from idl/skyrelay/v1/types.idl — do not edit."

# IDL primitive -> (C++ type, TS type, is_float)
PRIMITIVES = {
    "boolean": ("bool", "boolean", False),
    "octet": ("uint8_t", "number", False),
    "int8": ("int8_t", "number", False),
    "uint8": ("uint8_t", "number", False),
    "int16": ("int16_t", "number", False),
    "uint16": ("uint16_t", "number", False),
    "short": ("int16_t", "number", False),
    "int32": ("int32_t", "number", False),
    "uint32": ("uint32_t", "number", False),
    "long": ("int32_t", "number", False),
    "int64": ("int64_t", "number", False),
    "uint64": ("uint64_t", "number", False),
    "float": ("float", "number | null", True),
    "double": ("double", "number | null", True),
}


class IdlError(Exception):
    pass


@dataclass
class Field:
    name: str
    type: str          # primitive name, "string", enum name or struct name
    kind: str          # "prim", "string", "enum", "struct"
    key: bool
    unit: str
    line: int
    bound: int = 0
    bit: int = -1      # valid-mask bit, -1 when the field has none


@dataclass
class Struct:
    name: str
    fields: list = field(default_factory=list)
    has_header: bool = False

    @property
    def data_fields(self):
        return [f for f in self.fields if f.bit >= 0]


@dataclass
class Enum:
    name: str
    literals: list = field(default_factory=list)


@dataclass
class Model:
    namespace: list = field(default_factory=list)
    enums: list = field(default_factory=list)
    structs: list = field(default_factory=list)

    def struct(self, name):
        return next(s for s in self.structs if s.name == name)

    def enum(self, name):
        return next(e for e in self.enums if e.name == name)


TOKEN = re.compile(r"(//[^\n]*)|(/\*.*?\*/)|(@?[A-Za-z_][A-Za-z0-9_]*|\d+|\S)", re.S)


def tokenize(text):
    """Return (tokens, units). tokens are (text, line); units maps line -> unit."""
    toks, units = [], {}
    for m in TOKEN.finditer(text):
        line = text.count("\n", 0, m.start()) + 1
        if m.group(1):
            u = re.match(r"//\s*unit:\s*(\S+)\s*$", m.group(1))
            if u:
                units[line] = u.group(1)
        elif m.group(3):
            toks.append((m.group(3), line))
    return toks, units


class Parser:
    def __init__(self, text):
        self.toks, self.units = tokenize(text)
        self.i = 0
        self.model = Model()
        self.enum_names, self.struct_names = set(), set()

    def peek(self):
        return self.toks[self.i] if self.i < len(self.toks) else ("", self.toks[-1][1] if self.toks else 0)

    def next(self):
        t = self.peek()
        self.i += 1
        return t

    def err(self, line, msg):
        raise IdlError(f"line {line}: {msg}")

    def expect(self, text):
        t, line = self.next()
        if t != text:
            self.err(line, f"expected '{text}', found '{t}'")
        return line

    def ident(self):
        t, line = self.next()
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", t):
            self.err(line, f"expected identifier, found '{t}'")
        return t

    def parse(self):
        self.definitions(top=True)
        return self.model

    def definitions(self, top):
        while self.peek()[0]:
            t, line = self.peek()
            if t == "}":
                return
            annotations = self.annotations()
            t, line = self.next()
            if t == "module":
                name = self.ident()
                self.expect("{")
                self.model.namespace.append(name)
                self.definitions(top=False)
                self.expect("}")
                self.expect(";")
            elif t == "struct":
                self.struct(line)
            elif t == "enum":
                self.enum()
            else:
                self.err(line, f"{t} is not supported (modules, structs and enums only)")
            del annotations

    def annotations(self):
        out = []
        while self.peek()[0].startswith("@"):
            t, line = self.next()
            if t not in ("@appendable", "@key"):
                self.err(line, f"annotation {t} is not supported")
            out.append(t)
        return out

    def enum(self):
        e = Enum(self.ident())
        self.expect("{")
        while True:
            e.literals.append(self.ident())
            t, line = self.next()
            if t == "}":
                break
            if t != ",":
                self.err(line, f"expected ',' or '}}', found '{t}'")
        self.expect(";")
        self.model.enums.append(e)
        self.enum_names.add(e.name)

    def struct(self, line):
        s = Struct(self.ident())
        self.expect("{")
        while self.peek()[0] != "}":
            s.fields.append(self.member(s))
        self.expect("}")
        self.expect(";")
        self.assign_bits(s)
        self.model.structs.append(s)
        self.struct_names.add(s.name)

    def member(self, s):
        key = False
        for a in self.annotations():
            key = key or a == "@key"
        tname, line = self.next()
        bound = 0
        if tname == "string":
            self.expect("<")
            n, nline = self.next()
            if not n.isdigit():
                self.err(nline, "string bound must be a number")
            bound = int(n)
            self.expect(">")
            kind = "string"
        elif tname in PRIMITIVES:
            kind = "prim"
        elif tname in self.enum_names:
            kind = "enum"
        elif tname in self.struct_names:
            kind = "struct"
        elif tname in ("sequence", "map", "union", "bitset"):
            self.err(line, f"{tname} is not supported")
        else:
            self.err(line, f"unknown type '{tname}'")
        name_tok, name_line = self.peek()
        name = self.ident()
        self.expect(";")
        # The unit comment sits on the line of the terminating ';'.
        unit = self.units.get(self.toks[self.i - 1][1])
        if unit is None and kind != "struct":
            unit = self.units.get(name_line)
        if unit is None and kind != "struct":
            self.err(name_line, f"field '{name}' is missing a trailing '// unit: <unit>' comment")
        return Field(name, tname, kind, key, unit or "-", name_line, bound)

    def assign_bits(self, s):
        seen_header, bit = False, 0
        for f in s.fields:
            if f.name == "header" and f.type == "Header":
                seen_header = True
                s.has_header = True
                continue
            if seen_header and not f.key:
                f.bit = bit
                bit += 1
        if bit > 64:
            self.err(s.fields[0].line, f"struct {s.name} has {bit} data fields, valid_mask holds 64")


def parse(text):
    """Parse the restricted IDL subset into a Model."""
    p = Parser(text)
    model = p.parse()
    t, line = p.peek()
    if t:
        raise IdlError(f"line {line}: unexpected '{t}' at top level")
    return model


# ---------------------------------------------------------------- C++ -----

def ns_cpp(m):
    return "::".join(m.namespace)


def gen_json_hpp(m):
    ns = ns_cpp(m)
    o = [f"// {BANNER}", "#pragma once", "",
         "#include <cmath>", "", "#include <nlohmann/json.hpp>", "",
         "#include <skyrelay/dds/idl.hpp>", "",
         "// Enums become their literal name, NaN floats become null. An enum value",
         "// outside the known literals (a newer peer) also becomes null.", "",
         f"namespace {ns} {{", ""]
    for e in m.enums:
        o.append(f"inline nlohmann::json to_json_value({e.name} v) {{")
        o.append("  switch (v) {")
        for lit in e.literals:
            o.append(f'    case {e.name}::{lit}: return "{lit}";')
        o.append("  }")
        o.append("  return nullptr;")
        o.append("}")
        o.append("")
    for s in m.structs:
        o.append(f"inline nlohmann::json to_json_value(const {s.name}& v) {{")
        o.append("  nlohmann::json j = nlohmann::json::object();")
        for f in s.fields:
            acc = f"v.{f.name}()"
            if f.kind == "prim" and PRIMITIVES[f.type][2]:
                expr = f"std::isnan({acc}) ? nlohmann::json(nullptr) : nlohmann::json({acc})"
            elif f.kind in ("enum", "struct"):
                expr = f"to_json_value({acc})"
            else:
                expr = f"nlohmann::json({acc})"
            o.append(f'  j["{f.name}"] = {expr};')
        o.append("  return j;")
        o.append("}")
        o.append("")
    o.append(f"}}  // namespace {ns}")
    return "\n".join(o) + "\n"


def gen_valid_hpp(m):
    ns = ns_cpp(m)
    o = [f"// {BANNER}", "#pragma once", "", "#include <cstdint>", "",
         "// valid_mask bit i is the i-th data field after `header`.",
         f"namespace {ns}::valid {{", ""]
    for s in m.structs:
        if not s.data_fields:
            continue
        o.append(f"struct {s.name} {{")
        for f in s.data_fields:
            o.append(f"  static constexpr uint64_t {f.name} = 1ull << {f.bit};")
        o.append("};")
        o.append("")
    o.append(f"}}  // namespace {ns}::valid")
    return "\n".join(o) + "\n"


# ----------------------------------------------------------------- TS -----

def ts_type(f):
    if f.kind == "prim":
        return PRIMITIVES[f.type][1]
    if f.kind == "string":
        return "string"
    return f.type


def gen_ts(m):
    o = [f"// {BANNER}", ""]
    for e in m.enums:
        o.append(f"export type {e.name} =")
        o.append("\n".join(f'  | "{lit}"' for lit in e.literals) + ";")
        o.append("")
    for s in m.structs:
        o.append(f"export interface {s.name} {{")
        for f in s.fields:
            o.append(f"  {f.name}: {ts_type(f)};")
        o.append("}")
        o.append("")
    for s in m.structs:
        if not s.data_fields:
            continue
        o.append(f"export const {s.name}Valid = {{")
        for f in s.data_fields:
            if f.bit > 52:
                raise IdlError(f"{s.name}.{f.name}: bit {f.bit} exceeds the JS safe integer range")
            o.append(f"  {f.name}: {1 << f.bit},")
        o.append("} as const;")
        o.append("")
    return "\n".join(o).rstrip("\n") + "\n"


# ----------------------------------------------------------- Markdown -----

def cpp_type_label(f):
    if f.kind == "string":
        return f"string<{f.bound}>"
    return f.type


def gen_md(m):
    o = [f"<!-- {BANNER} -->", "", "# Contract v1 fields", "",
         "Bit is the position in `header.valid_mask`; `-` means the field has no bit.", ""]
    for s in m.structs:
        o.append(f"## {s.name}")
        o.append("")
        o.append("| field | type | bit | unit |")
        o.append("|---|---|---|---|")
        for f in s.fields:
            bit = str(f.bit) if f.bit >= 0 else "-"
            o.append(f"| `{f.name}` | `{cpp_type_label(f)}` | {bit} | {f.unit} |")
        o.append("")
    for e in m.enums:
        o.append(f"## {e.name}")
        o.append("")
        o.append(", ".join(f"`{lit}`" for lit in e.literals))
        o.append("")
    return "\n".join(o).rstrip("\n") + "\n"


def generate(m):
    """Return {relative path: file text} for every generated file."""
    return {
        JSON_HPP: gen_json_hpp(m),
        VALID_HPP: gen_valid_hpp(m),
        TS_PATH: gen_ts(m),
        MD_PATH: gen_md(m),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    ap.add_argument("--root", default=str(Path(__file__).resolve().parents[2]),
                    help="repository root (default: this checkout)")
    args = ap.parse_args(argv)
    root = Path(args.root)
    try:
        out = generate(parse((root / IDL_PATH).read_text(encoding="utf-8")))
    except (IdlError, OSError) as e:
        print(f"idl2gen: {e}", file=sys.stderr)
        return 2
    if args.check:
        stale = []
        for rel, text in out.items():
            p = root / rel
            if not p.exists() or p.read_text(encoding="utf-8") != text:
                stale.append(rel)
        for rel in stale:
            print(f"idl2gen: stale generated file: {rel}", file=sys.stderr)
        if stale:
            print("run: python3 tools/codegen/idl2gen.py", file=sys.stderr)
        return 1 if stale else 0
    for rel, text in out.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
